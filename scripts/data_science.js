function makeIndicators(prefix, stdCode, stdNum, grade, texts, codeGrade = null) {
  const gradeUpper = grade.toUpperCase();
  const cGrade = codeGrade || (grade.startsWith('p') ? `ป.${grade.slice(1)}` : `ม.${grade.slice(1)}`);
  return texts.map((text, idx) => {
    const num = idx + 1;
    const numPad = String(num).padStart(2, '0');
    return {
      id: `${prefix}-${stdNum}-${gradeUpper}-${numPad}`,
      code: `${stdCode} ${cGrade}/${num}`,
      text
    };
  });
}

function makeHighSchoolSpread(prefix, stdCode, stdNum, grades, texts, codeGrade) {
  const result = {};
  grades.forEach(grade => {
    result[grade] = makeIndicators(prefix, stdCode, stdNum, grade, texts, codeGrade);
  });
  return result;
}

function makeGradeLevels(config) {
  const grades = ['p1', 'p2', 'p3', 'p4', 'p5', 'p6', 'm1', 'm2', 'm3', 'm4', 'm5', 'm6'];
  const res = {};
  for (const g of grades) {
    res[g] = config[g] || [];
  }
  return res;
}

