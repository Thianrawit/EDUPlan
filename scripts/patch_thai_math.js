// Helper for Thai high school indicators (กระจายลง m4, m5, m6)
function makeThaiHighSchoolIndicators(stdNum, indicators) {
  const result = { m4: [], m5: [], m6: [] };
  ['m4', 'm5', 'm6'].forEach(grade => {
    const gradeUpper = grade.toUpperCase();
    result[grade] = indicators.map((text, idx) => {
      const num = idx + 1;
      const numPad = String(num).padStart(2, '0');
      return {
        id: `TH-${stdNum}-${gradeUpper}-${numPad}`,
        code: `ท ${stdNum} ม.4-6/${num}`,
        text
      };
    });
  });
  return result;
}

