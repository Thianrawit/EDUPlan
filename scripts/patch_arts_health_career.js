// Helper to build gradeLevels object
function makeGradeLevels(config) {
  const grades = ['p1', 'p2', 'p3', 'p4', 'p5', 'p6', 'm1', 'm2', 'm3', 'm4', 'm5', 'm6'];
  const gradeLevels = {};
  for (const g of grades) {
    gradeLevels[g] = config[g] || [];
  }
  return gradeLevels;
}

// Helper to spread high school indicators (ม.4 - ม.6)
function makeHighSchoolIndicators(prefix, stdCode, stdNum, indicators) {
  const result = { m4: [], m5: [], m6: [] };
  ['m4', 'm5', 'm6'].forEach(grade => {
    const gradeUpper = grade.toUpperCase();
    result[grade] = indicators.map((text, idx) => {
      const num = idx + 1;
      const numPad = String(num).padStart(2, '0');
      return {
        id: `${prefix}-${stdNum}-${gradeUpper}-${numPad}`,
        code: `${stdCode} ม.4-6/${num}`,
        text
      };
    });
  });
  return result;
}

